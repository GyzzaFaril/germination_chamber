/// Definisi breakpoint ukuran layar aplikasi
class AppBreakpoints {
  AppBreakpoints._();

  /// Batas maksimum layar Mobile (misal: smartphone vertikal)
  static const double mobile = 600.0;

  /// Batas maksimum layar Tablet (misal: tablet portrait/landscape)
  static const double tablet = 1024.0;

  /// Layar Desktop adalah layar dengan lebar > 1024.0
  static const double desktop = 1440.0;
}
